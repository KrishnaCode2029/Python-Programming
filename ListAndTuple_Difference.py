"""
Difference Between List and Tuple

1. Mutable:
   List is mutable, while Tuple is immutable.

2. Syntax:
   List uses square brackets [].
   Tuple uses parentheses ().

3. Can Change Values:
   In a List, we can change the values of elements.
   In a Tuple, we cannot change the values of elements.

4. Can Add/Remove:
   In a List, we can add new elements and remove existing elements.
   In a Tuple, we cannot add or remove elements.

5. Ordered:
   Both List and Tuple are ordered collections.
   This means the elements maintain their order and have fixed indexes.

6. Allows Duplicate Values:
   Both List and Tuple can contain duplicate values.

7. Performance:
   Tuples are generally slightly faster than Lists because Tuples are immutable.

8. Use:
   A List is useful when the data may change in the future.
   A Tuple is useful when the data should remain unchanged.
"""